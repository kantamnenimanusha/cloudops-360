<#
 Generates local/.env with strong random secrets and points the GitOps repo at your GitHub account.
 Nothing is sent anywhere; the files it writes are git-ignored.
 Requires a GitHub fine-grained token: Contents read on the app repo, Contents read+write on the GitOps repo.
#>
param(
    [Parameter(Mandatory = $true)][string]$GitHubUser,
    [string]$AppRepo = "cloudops-360",
    [string]$GitOpsRepo = "cloudops-360-gitops",
    [string]$GitOpsPath
)
. "$PSScriptRoot\_common.ps1"
$gitops = Get-GitOpsPath $GitOpsPath
$secure = Read-Host "GitHub token (input hidden)" -AsSecureString
$token = [System.Runtime.InteropServices.Marshal]::PtrToStringAuto([System.Runtime.InteropServices.Marshal]::SecureStringToBSTR($secure))
if (-not $token) { throw "A GitHub token is required (Jenkins pushes image tags to the GitOps repo)." }

New-Item -ItemType Directory -Force (Split-Path $EnvFile) | Out-Null
$lines = @(
    "# Generated by 01-configure.ps1 - git-ignored. Contains secrets: do not share.",
    "GITHUB_USER=$GitHubUser", "GITHUB_TOKEN=$token",
    "APP_REPO_URL=https://github.com/$GitHubUser/$AppRepo.git",
    "GITOPS_REPO_URL=https://github.com/$GitHubUser/$GitOpsRepo.git",
    "SONAR_DB_PASSWORD=$(New-Secret 24)", "SONAR_ADMIN_PASSWORD=$(New-Secret 18)", "SONAR_TOKEN=",
    "JENKINS_ADMIN_PASSWORD=$(New-Secret 18)", "JENKINS_RO_PASSWORD=$(New-Secret 18)",
    "JWT_SECRET=$(New-Secret 48)", "VIEWER_PASSWORD=$(New-Secret 18)", "ADMIN_PASSWORD=$(New-Secret 18)",
    "WEBHOOK_TOKEN=$(New-Secret 32)", "CHAOS_TOKEN=$(New-Secret 24)"
)
Set-Content -Path $EnvFile -Value $lines -Encoding ascii

# Dev .env for running the backend directly on the host (uvicorn)
$e = Read-DotEnv
$be = @("APP_ENV=dev", "JWT_SECRET=$($e.JWT_SECRET)", "VIEWER_PASSWORD=$($e.VIEWER_PASSWORD)", "ADMIN_PASSWORD=$($e.ADMIN_PASSWORD)",
    "WEBHOOK_TOKEN=$($e.WEBHOOK_TOKEN)", "ALLOWED_ORIGINS=http://localhost:5173",
    "PROMETHEUS_URL=http://localhost:9090", "ALERTMANAGER_URL=http://localhost:9093", "LOKI_URL=http://localhost:3100",
    "JENKINS_URL=http://localhost:8080", "JENKINS_USER=cloudops-ro", "JENKINS_PASSWORD=$($e.JENKINS_RO_PASSWORD)")
Set-Content -Path (Join-Path $Root "apps\backend\.env") -Value $be -Encoding ascii

# Point the GitOps repo at your GitHub account (the only non-secret value that needs your input)
$files = Get-ChildItem -Path $gitops -Recurse -Include *.yaml | Where-Object { (Get-Content $_.FullName -Raw) -match "__GITHUB_USER__" }
foreach ($f in $files) { (Get-Content $f.FullName -Raw).Replace("__GITHUB_USER__", $GitHubUser) | Set-Content -Path $f.FullName -NoNewline -Encoding utf8 }
Write-Host "Wrote $EnvFile and apps\backend\.env; updated $($files.Count) GitOps file(s)." -ForegroundColor Green
Write-Host "NEXT: create the two GitHub repos, push both folders (see README step 4), then run 02-create-cluster.ps1 and 03-start-ci.ps1"
Write-Host "Your dashboard login: viewer / (VIEWER_PASSWORD in local\.env)  admin / (ADMIN_PASSWORD)"
