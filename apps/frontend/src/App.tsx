import { useEffect, useState } from "react";
import { getToken, login, setToken } from "./api";
import { Alerts, CICD, Deployments, Infrastructure, Kubernetes, Logs, Monitoring, Overview, Security } from "./pages";

const PAGES: [string, () => any][] = [
  ["Overview", Overview], ["Infrastructure", Infrastructure], ["Kubernetes", Kubernetes], ["CI/CD", CICD],
  ["Security", Security], ["Monitoring", Monitoring], ["Logs", Logs], ["Alerts", Alerts], ["Deployments", Deployments],
];

function Login({ onDone }: { onDone: () => void }) {
  const [username, setUsername] = useState("viewer");
  const [password, setPassword] = useState("");
  const [error, setError] = useState("");
  const submit = async () => {
    try { await login(username, password); onDone(); } catch (e: any) { setError(e.message); }
  };
  return (
    <div className="login card">
      <h2>CloudOps 360</h2>
      <p className="muted">Sign in (credentials are generated by scripts/windows/01-configure.ps1 into .env files).</p>
      <input value={username} onChange={(e) => setUsername(e.target.value)} placeholder="username" autoComplete="username" />
      <input type="password" value={password} onChange={(e) => setPassword(e.target.value)} placeholder="password"
             autoComplete="current-password" onKeyDown={(e) => e.key === "Enter" && submit()} />
      <button onClick={submit}>Sign in</button>
      {error && <p className="error">{error}</p>}
    </div>
  );
}

export default function App() {
  const [authed, setAuthed] = useState(!!getToken());
  const [page, setPage] = useState(0);
  useEffect(() => {
    const f = () => setAuthed(false);
    window.addEventListener("auth-expired", f);
    return () => window.removeEventListener("auth-expired", f);
  }, []);
  if (!authed) return <Login onDone={() => setAuthed(true)} />;
  const Current = PAGES[page][1];
  return (
    <div className="layout">
      <nav>
        <h1>CloudOps 360</h1>
        {PAGES.map(([name], i) => (
          <button key={name} className={i === page ? "active" : ""} onClick={() => setPage(i)}>{name}</button>
        ))}
        <button className="signout" onClick={() => { setToken(null); setAuthed(false); }}>Sign out</button>
      </nav>
      <main><Current /></main>
    </div>
  );
}
